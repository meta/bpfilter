#pragma once

#include <stdint.h>

#include <bpfilter/verdict.h>

struct bf_matcher;
struct bf_codegen;
struct bf_rule;

/**
 * @file flavor.h
 *
 * "Flavor" as defined by bpfilter are types of BPF program, characterized by
 * the prototype of the main function, the valid returns values, and the
 * way they are attached to the kernel.
 *
 * A flavor is used to defines specific part of the BPF program for a
 * codegen. For example: access to the packet's data, return value...
 */

/**
 * @enum bf_flavor
 *
 * Define the BPF program flavours available to bpfilter.
 */
enum bf_flavor
{
    /**
     * BPF TC programs, attached directly to an interface:
     * - Input: `struct __sk_buff`
     * - Headers available: from L2
     * - Return code: 2 to drop, 0 to accept
     */
    BF_FLAVOR_TC,

    /**
     * BPF_NETFILTER programs, can be attached to any Netfilter hook available:
     * - Input: `struct bpf_nf_ctx`
     * - Headers available: from L3
     * - Return code: 0 to drop, 1 to accept
     */
    BF_FLAVOR_NF,

    /**
     * XDP BPF programs, attached directly to an interface:
     * - Input: `struct xdp_md`
     * - Headers available: from L2
     * - Return code: 1 to drop, 2 to accept
     */
    BF_FLAVOR_XDP,

    /**
     * cgroup_skb BPF programs are a middle ground between TC and BPF_NETFILTER
     * programs:
     * - Input: `struct __sk_buff`
     * - Headers available: from L3
     * - Return code: 0 to drop, 1 to accept
     */
    BF_FLAVOR_CGROUP_SKB,

    /**
     * cgroup_sock_addr BPF programs, attached to a cgroup to intercept
     * socket operations (connect, bind, sendmsg, recvmsg):
     * - Input: `struct bpf_sock_addr`
     * - No packet data; L3 protocol from the hook, L4 protocol from
     *   `bpf_sock_addr.protocol`
     * - Return code: 0 to drop, 1 to accept
     */
    BF_FLAVOR_CGROUP_SOCK_ADDR,
    _BF_FLAVOR_MAX,
};

/**
 * @struct bf_flavor_ops
 *
 * Define a set of operations that can be performed for a specific BPF flavor.
 *
 * @var bf_flavor_ops::gen_inline_epilogue
 *  Generate the epilogue of the BPF program.
 */
struct bf_flavor_ops
{
    /**
     * Generate the flavor-specific prologue of the BPF program.
     *
     * When this callback is called during the program generation, @c BPF_REG_1
     * contains the program's argument. It must then:
     * - Calculate and store the packet's size into the runtime context
     * - Store the input interface index into the runtime context
     * - If L2 is not available, set the L3 protocol ID into @c BPF_REG_7 and
     *   set @c l3_offset in the runtime context to 0.
     * - Call @ref bf_stub_parse_l2_ethhdr, @ref bf_stub_parse_l3_hdr, and
     *   @ref bf_stub_parse_l4_hdr depending on which headers are available.
     */
    int (*gen_inline_prologue)(struct bf_codegen *program);

    int (*gen_inline_epilogue)(struct bf_codegen *program);

    int (*gen_inline_set_mark)(struct bf_codegen *program, uint32_t mark);

    /**
     * @brief Generate bytecode to redirect a packet to another interface.
     *
     * @param program Program to generate bytecode for. Can't be NULL.
     * @param ifindex Target interface index.
     * @param dir Direction to redirect: ingress or egress.
     * @return 0 on success, negative errno on failure. Returns -ENOTSUP if the
     *         flavor doesn't support redirect.
     */
    int (*gen_inline_redirect)(struct bf_codegen *program, uint32_t ifindex,
                               enum bf_redirect_dir dir);

    /**
     * @brief Generate bytecode to reject a packet: reply to its sender, then
     * drop it.
     *
     * The generated bytecode must terminate the program. Packets the flavor
     * can't reply to must be dropped.
     *
     * @param program Program to generate bytecode for. Can't be NULL.
     * @param type Reply to send.
     * @return 0 on success, or a negative errno value on failure. Flavors
     *         which don't support REJECT leave this callback NULL.
     */
    int (*gen_inline_reject)(struct bf_codegen *program,
                             enum bf_reject_type type);

    /**
     * Generates a flavor-specific return code corresponding to the verdict.
     *
     * Note this function only needs to handle terminal verdicts - verdicts that
     * stop further packet processing. Non-terminal verdicts do not need return
     * codes and therefore do not need to be handled by get_verdict().
     *
     * @param verdict Verdict to convert. Must be a terminal verdict.
     * @param ret_code On success, set to the flavor-specific BPF return code.
     *        Can't be NULL.
     * @return 0 on success, or negative errno value on failure.
     */
    int (*get_verdict)(enum bf_verdict verdict, int *ret_code);

    /**
     * @brief Generate bytecode for a matcher. Required for all flavors.
     *
     * @param program Program being generated. Can't be NULL.
     * @param matcher Matcher to generate code for. Can't be NULL.
     * @return 0 on success, negative errno on error.
     */
    int (*gen_inline_matcher)(struct bf_codegen *program,
                              const struct bf_matcher *matcher);

    /**
     * @brief Generate bytecode for rule logging.
     *
     * Each flavor controls its own register setup and ELF stub selection.
     * `EMIT_FIXUP_ELFSTUB(program, BF_ELFSTUB_xxx)` should be the last
     * instruction emitted, so its return value remains in `r0` after the
     * callback returns. Required for all flavors.
     *
     * @param program Program being generated. Can't be NULL.
     * @param rule Rule whose log action to generate. Can't be NULL.
     * @return 0 on success, or negative errno on error.
     */
    int (*gen_inline_log)(struct bf_codegen *program,
                          const struct bf_rule *rule);
};

/**
 * Convert a bpfilter flavor to a string.
 *
 * @param flavor Flavor to convert. Must be valid.
 * @return String representation of @p flavor.
 */
const char *bf_flavor_to_str(enum bf_flavor flavor);
